import fs from 'node:fs/promises';
import path from 'node:path';
import {createRequire} from 'node:module';
import {pathToFileURL} from 'node:url';
import {nodeModules} from './runtime.mjs';
if(!nodeModules)throw Error('月榜导出需要设置 NINT_NODE_MODULES 为包含 @oai/artifact-tool 的捆绑 node_modules 路径');
const entry=createRequire(import.meta.url).resolve('@oai/artifact-tool',{paths:[path.dirname(nodeModules)]});
const {Workbook,SpreadsheetFile}=await import(pathToFileURL(entry).href);

const [payloadPath, outDir] = process.argv.slice(2);
const p = JSON.parse(await fs.readFile(payloadPath, 'utf8'));
if(await fs.stat(path.join(outDir,'店铺下载队列.json')).then(()=>true,()=>false))throw Error('已有队列，不覆盖进度；使用新的输出目录');
const wb = Workbook.create();
const s = wb.worksheets.add('QBT');
const data = [p.headers, ...p.rows];
s.getRange('A1:M101').values = data;
s.showGridLines = false;
s.getRange('A1:M101').format.font = {name:'Arial',size:10};
s.getRange('A1:M101').format.rowHeight = 30;
s.getRange('A1:M101').format.verticalAlignment = 'center';
s.getRange('A1:M1').format = {fill:'#26445F',font:{name:'Arial',size:10,bold:true,color:'#FFFFFF'},wrapText:true,horizontalAlignment:'center',rowHeight:48};
const widths = [8,32,35,29,14,41,16,20,20,18,13,28,20];
widths.forEach((width,i)=>s.getRangeByIndexes(0,i,101,1).format.columnWidth=width);
s.getRange('A2:A101').setNumberFormat('0');
s.getRange('G2:G101').setNumberFormat('#,##0');
s.getRange('H2:H101').setNumberFormat('#,##0.00');
s.getRange('I2:J101').setNumberFormat('0.00%');
s.getRange('K2:K101').setNumberFormat('0');
s.getRange('L2:L101').setNumberFormat('#,##0.00');
s.freezePanes.freezeRows(1);
s.tables.add('A1:M101',true,'Top100Shops');
const c = wb.worksheets.add('下载条件');
const conditions = [...p.conditions, ['保留范围','原始店铺详细数据按销量排名保留第1至100名'], ['来源文件',path.basename(p.source)], ['来源SHA256',p.sourceSha256]];
c.getRangeByIndexes(0,0,conditions.length,2).values=conditions;
c.showGridLines=false;
c.getRangeByIndexes(0,0,conditions.length,2).format = {font:{name:'Arial',size:10},rowHeight:28,verticalAlignment:'center'};
c.getRange('A1:B1').format = {fill:'#26445F',font:{bold:true,color:'#FFFFFF'}};
c.getRange('A1:A11').format.columnWidth=20;
c.getRange('B1:B11').format.columnWidth=90;
wb.recalculate();
await fs.mkdir(path.join(outDir,'evidence'),{recursive:true});
for (const [sheetName,range,file] of [['QBT','A1:E12','preview-main.png'],['QBT','G1:M12','preview-metrics.png'],['下载条件','A1:B11','preview-conditions.png']]) {
 const blob=await wb.render({sheetName,range,scale:1.5,format:'png'});
 await fs.writeFile(path.join(outDir,'evidence',file),new Uint8Array(await blob.arrayBuffer()));
}
const file=path.join(outDir,`童装_婴儿装_亲子装_天猫_热销店铺前100_销量_${p.month}.xlsx`);
await (await SpreadsheetFile.exportXlsx(wb)).save(file);
await fs.writeFile(path.join(outDir,'店铺下载队列.json'),JSON.stringify({month:p.month,sourceWorkbook:file,sourceRanking:p.source,scope:'母婴 > 童装/婴儿装/亲子装 / 天猫全部',sort:'销量降序',sourceWorkbookSha256:(await import('node:crypto')).createHash('sha256').update(await fs.readFile(file)).digest('hex'),status:'ranking_verified_shops_pending',shops:p.rows.map(row=>({rank:row[0],searchName:row[1],shopName:row[2],shopUrl:row[5],status:'pending'}))},null,2));
console.log(JSON.stringify({file,rows:p.rows.length}));
